// What each story stage actually holds (for writing the pre-stage story scenes): npx vite-node scripts/stage-facts.ts > docs/stage-facts.md
import { MOBS } from '../src/sim/mobs';
import { STAGES, WORLDS } from '../src/sim/stages';
import { dropName } from '../src/sim/drops';
import { HAZARD_NAMES } from './stage-facts-hazards';

const out: string[] = ['# Stage facts (generated by scripts/stage-facts.ts)', '',
  'Every normal stage: 2-3 small maps (stages 1-3: 2) with ladders and platforms; monsters respawn. Each map\'s EXIT PORTAL',
  'opens when you hand in the drops it wants (dropped by specific monsters). The last map is the BOSS ROOM with the',
  'boss-room foe asleep inside. Spare drops stay in the bag; a full set lets you skip straight to the boss next time.',
  'Stage 5: the boss room holds the world\'s champion (or, in Worlds 1-5, your nemesis). Stage 10: the world boss.', ''];
for (const w of WORLDS) {
  out.push(`## World ${w.id}: ${w.name} (hazard: ${w.hazardName ? `${w.hazardName.toLowerCase()}: hot caramel drips from a toffee-apple dipping rack and leaves a sticky puddle` : HAZARD_NAMES[w.hazard] ?? w.hazard})`);
  for (let n = 1; n <= 10; n++) {
    const s = STAGES.find(q => q.id === `${w.id}-${n}`)!;
    const zones = s.maps!.filter(m => m.kind === 'zone');
    const wants = zones.map((m, i) => `map ${i + 1}: ${m.goal?.kind === 'collect' ? m.goal.wants.map(q => `${q.n} ${dropName(q.mob)} (${MOBS[q.mob].name})`).join(' + ') : m.goal?.kind}`).join('; ');
    const extra = [
      [3, 7, 9].includes(n) ? 'a Lunchbox Mimic hides in map 1 (looks like a loot box)' : '',
      s.objective?.kind === 'escort' ? 'ESCORT: a lost Crumblet follows you and must not get hurt too badly; it hides in the boss room' : '',
      s.objective?.kind === 'fetch' ? `RACE: grab the Recipe Scroll high up in map 2 within ${s.objective.t} seconds` : '',
      s.objective?.kind === 'survive' ? `HOLD OUT: monsters pour in for ${s.objective.t} seconds in map 2` : '',
      n === 7 ? 'SECRET: a bouncy sponge past the end of map 2 leads to a hidden ledge with a key chest' : '',
    ].filter(Boolean).join('; ');
    const foe = s.mobs[0] ? MOBS[s.mobs[0].kind].name : '?';
    out.push(`- **${s.id} ${s.name}** — boss room: **${n === 5 && w.id <= 5 ? `${foe} (or your nemesis)` : foe}**. Drops wanted: ${wants}.${extra ? ' ' + extra + '.' : ''}`);
  }
  out.push('');
}
console.log(out.join('\n'));
