// In-stage banter bubbles: node scripts/banter-shot.mjs → shots/banter-taunt.png, banter-quip.png
import { spawn } from 'node:child_process';
import { chromium } from 'playwright-core';
const PORT = 5319, url = `http://localhost:${PORT}/?touch`;
const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--port', String(PORT), '--strictPort'], { stdio: 'pipe' });
const wait = ms => new Promise(r => setTimeout(r, ms));
await wait(3000);
const b = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const ctx = await b.newContext({ viewport: { width: 844, height: 390 }, deviceScaleFactor: Number(process.argv[2] ?? 1), isMobile: true, hasTouch: true });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', e => errs.push(e.message));
await p.goto(url);
await p.evaluate(() => localStorage.clear());
await p.reload();
for (let i = 0; i < 60; i++) { if (await p.evaluate(() => !!window.__kkq).catch(() => false)) break; await wait(250); }
await p.evaluate(() => document.querySelector('#title .play')?.click());
await wait(600);
await p.evaluate(() => { const s = window.__kkq.save; s.selected = 8; if (!s.unlocked.includes(8)) s.unlocked.push(8); s.heroes[8].level = 20; window.__kkq.play('2-3'); });
await wait(1500);
await p.evaluate(() => { const w = window.__kkq.world(), h = w.hero; h.inv = 99; for (const m of w.mobs) { m.hp = 0; m.state = 'dead'; } for (const [k, dx] of [['pickle', 160], ['milk', 300]]) w.spawnMob(k, h.x + dx, 15); });
await wait(1200);
await p.screenshot({ path: 'shots/banter-taunt.png' });
await p.evaluate(() => { const w = window.__kkq.world(); w.hero.hp = w.hero.d.maxHp * 0.2; });
await wait(700);
await p.screenshot({ path: 'shots/banter-quip.png' });
console.log(errs.length ? errs : 'no errors');
await b.close();
server.kill();
process.exit(0);
